/**
 * GARDE DE COUVERTURE DE L'INSPECTEUR — toute propriété que le lecteur reçoit a un contrôle.
 *
 * Règle du propriétaire, 22/09/2026 : « je veux tout pouvoir modifier dans le builder ce que les
 * users vont recevoir sans exception !! ». L'inventaire du même jour
 * (`tasks/inventaire-builder-editable-2026-09-22.md`) a compté 56 propriétés de bloc que le
 * compilateur LIT et qu'aucun champ n'ÉCRIT : un look de une, une barre multicolore, une icône
 * sociale… posés par l'import des maquettes, rendus chez l'abonné, et impossibles à changer.
 *
 * ⛔ LA LISTE DES CLÉS VIENT DU SCHÉMA, JAMAIS D'UNE LISTE TAPÉE ICI. Chaque clé de chaque variante
 * de `Block` (et des sous-objets `lead`, `card`, `midSection`, `cardRule`, des éléments de liste,
 * de `Theme`, de `Meta`, de `BoxStyle`) est lue dans l'objet Zod. Une propriété AJOUTÉE au schéma
 * sans contrôle fait donc rougir ce banc tout de suite — c'est son rôle, y compris quand un autre
 * chantier l'ajoute en parallèle.
 *
 * ⛔ « ÉCRITE » = UNE CLÉ LITTÉRALE DANS L'ARGUMENT D'UN APPEL D'ÉCRITURE (`patch`, `onPatch`, `set`,
 * `patchPart`…), dans la région de code qui édite ce type. Le source est lu par le compilateur
 * TypeScript : un commentaire, une chaîne ou un attribut JSX ne comptent pas, et une clé envoyée à
 * `fetch` (le corps de l'aperçu d'un flux porte `count`, `orderby`…) non plus.
 *
 * ⛔ L'EXEMPTION EST NOMINATIVE ET JUSTIFIÉE. Seules des propriétés que le lecteur ne reçoit pas y
 * figurent, chacune avec sa raison ; une exemption qui ne désigne plus aucune clé du schéma échoue.
 */
import { describe, expect, test } from "bun:test";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import ts from "typescript";
import { Block, BoxStyle, Meta, Spacing, Theme, VisibleIf } from "@nf/render/schema";
import { unwrapSchema, type ShapeHolder } from "./schema-bounds";

/* ------------------------------------------------------------------ *
 * 1. Les clés, dérivées du schéma
 * ------------------------------------------------------------------ */

/**
 * Clés dont on ne DESCEND PAS : elles sont écrites d'un bloc par leur propre éditeur, ou vérifiées
 * ailleurs dans ce banc (`style` contre le panneau Style).
 */
const OPAQUE_KEYS = new Set([
  "paragraphs", // texte riche : TextEditor réécrit les paragraphes entiers
  "previewItems", // aperçu d'un flux : écrit en bloc par « Refresh preview », jamais envoyé
  "style", // BoxStyle : vérifié une seule fois, contre StylePanel + MobilePanel
  "visibleIf", // condition : écrite entière par le panneau Rules
]);
/** Objets écrits d'un seul tenant par un champ dédié (SpacingInput…). */
const OPAQUE_SCHEMAS = new Set<unknown>([Spacing, BoxStyle, VisibleIf]);

/** Un chemin de propriété : `["article-feed", "lead", "titleFont"]`. */
type Path = string[];

function leafPaths(object: ShapeHolder, prefix: Path): Path[] {
  const out: Path[] = [];
  for (const [key, raw] of Object.entries(object.shape)) {
    const path = [...prefix, key];
    const inner = unwrapSchema(raw);
    if (OPAQUE_KEYS.has(key) || OPAQUE_SCHEMAS.has(inner)) {
      out.push(path);
      continue;
    }
    if (inner?.def?.type === "object" && inner.shape) {
      out.push(path, ...leafPaths(inner as ShapeHolder, path));
      continue;
    }
    if (inner?.def?.type === "array") {
      const element = unwrapSchema(inner.def.element);
      out.push(path);
      if (element?.def?.type === "object" && element.shape && !OPAQUE_SCHEMAS.has(element)) {
        out.push(...leafPaths(element as ShapeHolder, path));
      }
      continue;
    }
    out.push(path);
  }
  return out;
}

const BLOCK_OPTIONS = (Block as unknown as { options: ShapeHolder[] }).options;
const typeOf = (option: ShapeHolder): string => {
  const literal = unwrapSchema(option.shape.type) as { def?: { values?: unknown[] } };
  const value = literal.def?.values?.[0];
  if (typeof value !== "string") throw new Error("Block option without a literal `type`");
  return value;
};

const BLOCK_PATHS: Path[] = BLOCK_OPTIONS.flatMap((option) => leafPaths(option, [typeOf(option)]));
const THEME_PATHS = leafPaths(Theme as unknown as ShapeHolder, ["theme"]);
const META_PATHS = leafPaths(Meta as unknown as ShapeHolder, ["meta"]);
const STYLE_PATHS = leafPaths(BoxStyle as unknown as ShapeHolder, ["style"]);
const ALL_PATHS = [...BLOCK_PATHS, ...THEME_PATHS, ...META_PATHS, ...STYLE_PATHS];

/* ------------------------------------------------------------------ *
 * 2. Exemptions — des propriétés que le lecteur ne reçoit pas
 * ------------------------------------------------------------------ */

/** `*` = toute variante de bloc. Chaque raison tient sur une ligne. */
const ALLOWLIST: Record<string, string> = {
  "*.id": "identity of the block, generated by the builder — never rendered",
  "*.type": "the block kind itself — changing it means adding another block",
  "article.source": "import provenance and its sub-keys (post id, fetch date, pin) — never emitted in the email",
  "meta.assetSlug": "the brand the template belongs to, fixed at creation — not part of the email",
};

/** Une exemption couvre la clé ET tout ce qu'elle contient (`article.source.pinned`…). */
const allowed = (path: Path) =>
  path.some((_, i) => ALLOWLIST[path.slice(0, i + 1).join(".")] !== undefined) ||
  (path.length === 2 && ALLOWLIST[`*.${path[1]}`] !== undefined && BLOCK_OPTIONS.some((o) => typeOf(o) === path[0]));

/* ------------------------------------------------------------------ *
 * 3. Où chaque propriété doit être écrite
 * ------------------------------------------------------------------ */

/**
 * `case:x` = le corps du `case "x"` de `BlockContent`. Sinon, une fonction nommée.
 *
 * Régions ajoutées le 22/09/2026 (lot 1b, réglages de `NEW_PROPS_2026_09_22`) — des éditeurs
 * PARTAGÉS, montés dans l'éditeur du bloc et qui écrivent par le `patch` / `onPatch` qu'il leur
 * passe, exactement comme `ArticleLookFields` pour l'article :
 *  • `CardButtonFields` : le jeu du bouton de carte (fond, texte, taille, graisse, marge, rayon),
 *    le même pour pick, promo, encart, article et looks du flux ;
 *  • `ButtonLookFields`, `MenuLookFields`, `SocialLookFields` : l'apparence du bouton, du menu et
 *    des icônes, rendues dans leur `case` ;
 *  • `DocumentOutputFields`, `LanguageDefaultsFields` : l'onglet du navigateur, la version texte et
 *    les défauts de langue, rendus dans `DocumentSettings` ;
 *  • `FeedCardFields` : les réglages des cartes du flux (disposition depuis le 23/09, nombre de unes,
 *    surtitre, heure, libellé),
 *    SORTIS de `FeedEditor` sans hook pour que le banc des contrôles puisse les déclencher ;
 *  • `MenuItemsEditor` (23/09/2026) : les liens du menu en cartes repliables, sortis du `case "menu"`
 *    sans hook pour la même raison — comme `SocialItemsEditor` pour les liens sociaux.
 * ⛔ Ce n'est PAS une exemption : chaque clé doit toujours y être écrite en toutes lettres, et le
 * test « chaque région nommée existe et chaque éditeur est rendu » échoue sur une région jamais montée.
 */
const BLOCK_REGIONS: Record<string, string[]> = {
  text: ["TextEditor"],
  image: ["case:image"],
  button: ["case:button", "ButtonLookFields"],
  divider: ["case:divider", "DividerSegmentsEditor"],
  spacer: ["case:spacer"],
  html: ["case:html"],
  social: ["case:social", "SocialItemsEditor", "SocialLookFields"],
  menu: ["case:menu", "MenuItemsEditor", "MenuLookFields"],
  pick: ["PickEditor", "CardButtonFields"],
  odds_table: ["OddsTableEditor"],
  standings: ["StandingsEditor"],
  scoreboard: ["ScoreboardEditor"],
  article: ["ArticleEditor", "ArticleLookFields", "CardButtonFields"],
  "article-feed": ["FeedEditor", "FeedCardFields", "FeedLookSections"],
  section_title: ["SectionTitleEditor"],
  callout: ["CalloutEditor", "CardButtonFields"],
  promo: ["PromoEditor", "CardButtonFields"],
  footer_legal: ["LegalFooterPicker"],
};
/** Sous-objets du flux : chacun a SON éditeur, qui écrit via `patchPart`. */
const FEED_PART_REGIONS: Record<string, string[]> = {
  lead: ["ArticleLookFields", "CardButtonFields"],
  card: ["ArticleLookFields", "CardButtonFields"],
  midSection: ["MidSectionFields"],
  cardRule: ["CardRuleFields"],
};
/** Réglages du document rendus dans `DocumentSettings` par des éditeurs partagés (voir plus haut). */
const META_REGIONS = [
  "DocumentSettings",
  "LocaleField",
  "BrandPartialsField",
  "DocumentOutputFields",
  "LanguageDefaultsFields",
];
/** Communes à tous les blocs : le style et la condition s'écrivent depuis les onglets du panneau. */
const COMMON_BLOCK_REGIONS: Record<string, string[]> = { style: ["Inspector"], visibleIf: ["Inspector"] };

function regionsFor(path: Path): string[] {
  const [head, first] = path;
  if (head === "theme") return ["ThemePanel", "WebFontsEditor"];
  if (head === "meta") return META_REGIONS;
  if (head === "style") return ["StylePanel", "MobilePanel"];
  if (path.length === 2 && COMMON_BLOCK_REGIONS[first] !== undefined) return COMMON_BLOCK_REGIONS[first];
  if (head === "article-feed" && FEED_PART_REGIONS[first] !== undefined) {
    // Le sous-objet lui-même est créé ou retiré depuis la section du flux ; ses clés, dans son éditeur.
    return path.length > 2 ? FEED_PART_REGIONS[first] : ["FeedLookSections", ...FEED_PART_REGIONS[first]];
  }
  const regions = BLOCK_REGIONS[head];
  if (regions === undefined) throw new Error(`no inspector region mapped for block type "${head}"`);
  return regions;
}

/* ------------------------------------------------------------------ *
 * 4. Lecture du source par le compilateur TypeScript
 * ------------------------------------------------------------------ */

const FILES = ["inspector.tsx", "article-look-fields.tsx", "extra-fields.tsx", "legal-footer-picker.tsx"];
/** Les appels qui ÉCRIVENT dans le document. `setCaret`, `setBusy`… n'en sont pas. */
const WRITERS = new Set([
  "patch",
  "onPatch",
  "patchPart",
  "patchBlock",
  "patchRow",
  "patchColumn",
  "set",
  "setItem",
  "setRow",
  "setSegment",
  "setFont",
  "onChange",
  "dispatch",
]);

const sources = FILES.map((name) =>
  ts.createSourceFile(name, readFileSync(join(import.meta.dir, name), "utf8"), ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX),
);

/** Toutes les régions nommées : fonctions déclarées, et `case "x":` du `switch` de BlockContent. */
const regions = new Map<string, ts.Node>();
for (const sf of sources) {
  const visit = (node: ts.Node) => {
    if (ts.isFunctionDeclaration(node) && node.name) regions.set(node.name.text, node);
    if (ts.isVariableDeclaration(node) && ts.isIdentifier(node.name) && node.initializer && ts.isArrowFunction(node.initializer)) {
      regions.set(node.name.text, node.initializer);
    }
    ts.forEachChild(node, visit);
  };
  visit(sf);
}
const blockContent = regions.get("BlockContent");
if (blockContent) {
  const visit = (node: ts.Node) => {
    if (ts.isCaseClause(node) && ts.isStringLiteral(node.expression)) regions.set(`case:${node.expression.text}`, node);
    ts.forEachChild(node, visit);
  };
  visit(blockContent);
}

const calleeName = (call: ts.CallExpression): string | undefined =>
  ts.isIdentifier(call.expression)
    ? call.expression.text
    : ts.isPropertyAccessExpression(call.expression)
      ? call.expression.name.text
      : undefined;

const keyName = (name: ts.PropertyName): string | undefined =>
  ts.isIdentifier(name) || ts.isStringLiteral(name) ? name.text : undefined;

/**
 * Les clés qu'une région ÉCRIT : clés d'objets littéraux (y compris abrégées) sous les arguments
 * d'un appel d'écriture, et nom de sous-objet passé en toutes lettres à `patchPart("lead", …)`.
 */
function writtenKeys(region: ts.Node): Set<string> {
  const keys = new Set<string>();
  const collect = (node: ts.Node) => {
    if (ts.isPropertyAssignment(node)) {
      const k = keyName(node.name);
      if (k !== undefined) keys.add(k);
    }
    if (ts.isShorthandPropertyAssignment(node)) keys.add(node.name.text);
    ts.forEachChild(node, collect);
  };
  const visit = (node: ts.Node) => {
    if (ts.isCallExpression(node)) {
      const name = calleeName(node);
      if (name !== undefined && WRITERS.has(name)) {
        for (const arg of node.arguments) collect(arg);
        if (name === "patchPart" && node.arguments[0] && ts.isStringLiteral(node.arguments[0])) {
          keys.add(node.arguments[0].text);
        }
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(region);
  return keys;
}

const writtenCache = new Map<string, Set<string>>();
function writtenIn(regionName: string): Set<string> {
  const cached = writtenCache.get(regionName);
  if (cached) return cached;
  const region = regions.get(regionName);
  if (region === undefined) throw new Error(`region "${regionName}" not found in ${FILES.join(", ")}`);
  const keys = writtenKeys(region);
  writtenCache.set(regionName, keys);
  return keys;
}

/** Les composants rendus quelque part en JSX (`<Name …>`). */
const rendered = new Set<string>();
for (const sf of sources) {
  const visit = (node: ts.Node) => {
    if ((ts.isJsxOpeningElement(node) || ts.isJsxSelfClosingElement(node)) && ts.isIdentifier(node.tagName)) {
      rendered.add(node.tagName.text);
    }
    ts.forEachChild(node, visit);
  };
  visit(sf);
}

/* ------------------------------------------------------------------ *
 * 5. Le garde
 * ------------------------------------------------------------------ */

describe("inspector coverage — every prop the reader receives has a control", () => {
  test("la dérivation voit bien le schéma (et pas une liste qui aurait rétréci)", () => {
    const joined = new Set(ALL_PATHS.map((p) => p.join(".")));
    // Des témoins de chaque étage : si l'un manque, c'est la dérivation qui est cassée, pas l'inspecteur.
    for (const witness of [
      "article.imageWidthPct",
      "article.ctaStyle",
      "article-feed.lead.ctaStyle",
      "article-feed.card.kickerText",
      "article-feed.midSection.label",
      "article-feed.cardRule.thickness",
      "social.items.iconSrc",
      "divider.segments.widthPct",
      "theme.webFonts.href",
      "meta.locale",
      "meta.headerPartialId",
      "style.fontSizeMobile",
    ]) {
      expect(joined.has(witness)).toBe(true);
    }
    expect(BLOCK_OPTIONS.length).toBe(Object.keys(BLOCK_REGIONS).length);
  });

  test("chaque type de bloc a sa région d'édition", () => {
    const unmapped = BLOCK_OPTIONS.map(typeOf).filter((t) => BLOCK_REGIONS[t] === undefined);
    expect(unmapped).toEqual([]);
  });

  test("chaque région nommée existe et chaque éditeur est rendu", () => {
    const names = new Set([
      ...Object.values(BLOCK_REGIONS).flat(),
      ...Object.values(FEED_PART_REGIONS).flat(),
      ...Object.values(COMMON_BLOCK_REGIONS).flat(),
      "ThemePanel",
      "WebFontsEditor",
      ...META_REGIONS,
      "StylePanel",
      "MobilePanel",
    ]);
    const missing = [...names].filter((n) => !regions.has(n));
    expect(missing).toEqual([]);
    // Une fonction jamais montée écrirait ses clés dans le vide : le garde serait vert pour rien.
    const orphans = [...names].filter((n) => !n.startsWith("case:") && n !== "Inspector" && !rendered.has(n));
    expect(orphans).toEqual([]);
  });

  test("chaque exemption désigne une clé qui existe encore", () => {
    const joined = new Set(ALL_PATHS.map((p) => p.join(".")));
    const stale = Object.keys(ALLOWLIST).filter((k) =>
      k.startsWith("*.") ? !BLOCK_PATHS.some((p) => p.length === 2 && p[1] === k.slice(2)) : !joined.has(k),
    );
    expect(stale).toEqual([]);
  });

  test("⛔ aucune propriété du schéma sans contrôle", () => {
    const uncovered: string[] = [];
    for (const path of ALL_PATHS) {
      if (allowed(path)) continue;
      const key = path[path.length - 1];
      const regionNames = regionsFor(path);
      if (!regionNames.some((r) => writtenIn(r).has(key))) {
        uncovered.push(`${path.join(".")} — no control writes \`${key}\` in ${regionNames.join(" / ")}`);
      }
    }
    expect(uncovered).toEqual([]);
  });

  test("⛔ lead / card / midSection / cardRule ne passent JAMAIS par une fusion à un niveau", () => {
    // `updateBlock` fusionne au premier niveau : `patch({ lead: { titleFont } })` effacerait le reste
    // de la une. Seul `patchPart` (→ `updateBlockPart`) a le droit d'écrire ces sous-objets.
    const offenders: string[] = [];
    for (const sf of sources) {
      const visit = (node: ts.Node) => {
        if (ts.isCallExpression(node)) {
          const name = calleeName(node);
          if (name !== undefined && name !== "patchPart" && WRITERS.has(name)) {
            for (const arg of node.arguments) {
              if (!ts.isObjectLiteralExpression(arg)) continue;
              for (const prop of arg.properties) {
                const k =
                  ts.isPropertyAssignment(prop) || ts.isShorthandPropertyAssignment(prop) ? keyName(prop.name) : undefined;
                if (k !== undefined && FEED_PART_REGIONS[k] !== undefined) {
                  const { line } = sf.getLineAndCharacterOfPosition(node.getStart(sf));
                  offenders.push(`${sf.fileName}:${line + 1} ${name}({ ${k}: … })`);
                }
              }
            }
          }
        }
        ts.forEachChild(node, visit);
      };
      visit(sf);
    }
    expect(offenders).toEqual([]);
    // Et la contre-épreuve : les deux looks sont bien écrits par `patchPart`.
    expect(writtenIn("FeedLookSections").has("lead")).toBe(true);
    expect(writtenIn("FeedLookSections").has("card")).toBe(true);
  });
});
